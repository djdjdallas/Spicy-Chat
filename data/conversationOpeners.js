// Get all openers in a category
export const getOpenersByCategory = (categoryId) => {
  return openers[categoryId] || [];
};

// Get a random opener from a specific category
export const getRandomOpener = (categoryId) => {
  const categoryOpeners = openers[categoryId];
  if (!categoryOpeners || categoryOpeners.length === 0) return null;
  return categoryOpeners[Math.floor(Math.random() * categoryOpeners.length)];
};

// Get all openers flattened into a single array
export const getAllOpeners = () => {
  return Object.values(openers).flat();
};

// Search openers by text
export const searchOpeners = (query) => {
  const lowercaseQuery = query.toLowerCase();
  return getAllOpeners().filter(
    (opener) =>
      opener.text.toLowerCase().includes(lowercaseQuery) ||
      opener.context.toLowerCase().includes(lowercaseQuery)
  );
};
