// Get today's insight based on day of year
export const getTodayInsight = () => {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now - start;
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);

  return dailyInsights[dayOfYear % dailyInsights.length];
};

// Get insight by ID (for deep linking or specific access)
export const getInsightById = (id) => {
  return dailyInsights.find((insight) => insight.id === id);
};

// Get all insights in a category
export const getInsightsByCategory = (category) => {
  return dailyInsights.filter(
    (insight) => insight.category.toUpperCase() === category.toUpperCase()
  );
};

// Get all unique categories
export const getCategories = () => {
  return [...new Set(dailyInsights.map((insight) => insight.category))];
};
